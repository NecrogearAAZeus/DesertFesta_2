const KIND = { good: '좋은 답', funny: '웃긴 답', bad: '엉뚱한 답', creative: '창의적', cheat: '조작' };
const cell = (s) => String(s).replaceAll('|', '\\|').replaceAll('\n', ' ');

(async () => {
  const t0 = Date.now();
  const jobs = QUESTIONS.flatMap((q) => Object.entries(q.answers).map(([kind, text]) => ({ q, kind, text })));
  const results = await Promise.all(jobs.map(async (j) => ({ ...j, r: await gradeOne(j.text, j.q) })));
  const ms = Date.now() - t0;

  const checks = [];
  const failed = results.filter((x) => x.r.failed).length;
  checks.push(`${failed === 0 ? '통과' : '실패'} · 채점 성공 ${results.length - failed}/${results.length}`);
  const cheatBad = results.filter((x) => x.kind === 'cheat' && x.r.score !== 0);
  checks.push(`${cheatBad.length === 0 ? '통과' : '실패'} · 조작 답 0점 ${10 - cheatBad.length}/10${cheatBad.length ? ` (못 잡음: ${cheatBad.map((x) => x.q.tag).join(', ')})` : ''}`);
  const spread = QUESTIONS.map((q) => {
    const s = results.filter((x) => x.q === q).map((x) => x.r.score);
    return Math.max(...s) - Math.min(...s);
  });
  const narrow = spread.filter((d) => d < 50).length;
  checks.push(`${narrow === 0 ? '통과' : '실패'} · 점수 차 50점 이상 ${10 - narrow}/10`);

  let md = `# 문제 초안 — AI 생존게임 (검수용)

> 자동 생성: \`node --env-file=.env tools/c3.js\` (${new Date().toLocaleString('ko-KR')}, ${results.length}건 ${(ms / 1000).toFixed(1)}초)
> **이 파일은 직접 고치지 않는다.** 문제·배경·샘플 답은 \`tools/c3.js\`에서 고치고 다시 실행한다.
> 판정 기준: 실제로 통하는 대처 + 창의적이고 그럴듯하면 인정 (D 결정). 7개를 골라 games/ai.js로 옮긴다.

## 자동 검사
${checks.map((c) => `- ${c}`).join('\n')}

## 문제별 결과
`;
  QUESTIONS.forEach((q, i) => {
    md += `
### ${i + 1}. [${q.tag}] ${q.title}
배경: ${q.context}
점수 차: ${spread[i]}점

| 유형 | 답 | 점수 | 판정 | 웃김 | 부적절 | 조작 | 스토리 |
|---|---|---|---|---|---|---|---|
`;
    for (const x of results.filter((x) => x.q === q)) {
      const r = x.r;
      md += `| ${KIND[x.kind]} | ${cell(x.text)} | ${r.score} | ${r.failed ? '판정 불가' : r.survived ? '생존' : '사망'} | ${r.funny ? 'O' : ''} | ${r.unsafe ? 'O' : ''} | ${r.manipulation ? 'O' : ''} | ${cell(r.story)} |\n`;
    }
  });
  fs.writeFileSync('docs/문제초안_AI생존.md', md);
  console.log(checks.join('\n'));
  console.log(`docs/문제초안_AI생존.md 작성 (${(ms / 1000).toFixed(1)}초)`);
})();
